import {createHash} from 'node:crypto';
import {readdir, readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {build} from 'esbuild';

const root = fileURLToPath(new URL('./', import.meta.url));
const files = (await readdir(new URL('src/', import.meta.url), {recursive: true}))
  .map(name => name.replaceAll('\\', '/')).filter(name => name.endsWith('.ts') && name !== 'build-info.ts').sort();
const hash = createHash('sha256');
for (const name of files) {
  hash.update(name).update('\0').update((await readFile(new URL(`src/${name}`, import.meta.url), 'utf8')).replaceAll('\r\n', '\n')).update('\0');
}
await writeFile(new URL('src/build-info.ts', import.meta.url),
  `/** Generated by build.mjs; identifies the shared calculation implementation. */\nexport const ENGINE_VERSION = '${hash.digest('hex')}';\n`);
const typecheck = process.argv.includes('--typecheck');
const tsc = spawnSync(process.execPath, [fileURLToPath(new URL('../../node_modules/typescript/bin/tsc', import.meta.url)),
  '--project', root, ...(typecheck ? ['--noEmit'] : [])], {stdio: 'inherit'});
if (tsc.status !== 0) process.exit(tsc.status ?? 1);
if (!typecheck) {
  await build({absWorkingDir: root, entryPoints: ['src/index.ts'], bundle: true, format: 'esm',
    platform: 'browser', target: 'es2022', outfile: 'dist/browser/engine.js', logLevel: 'info'});
}
